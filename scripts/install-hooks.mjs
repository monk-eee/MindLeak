#!/usr/bin/env node
// Install the Git hooks pre-commit must not own.
//
// pre-commit snapshots every unstaged change to a patch file in a shared,
// user-level cache directory, discards the working tree, runs the hooks, and
// restores the patch afterwards. For `pre-commit` and `pre-push` that is the
// price of admission: those hooks exist to judge what is about to be committed
// or pushed, so they need the tree to hold exactly that and nothing else.
//
// For `post-checkout` it is pure downside. `git checkout` commits nothing, so
// there is nothing to isolate — and the only hook this repository runs at that
// stage (`worktree-owner --stage=post-checkout`, ADR-0038) writes an ownership
// marker and never reads the working tree at all. The snapshot buys nothing and
// costs a window in which the whole tree lives in a file outside the repository.
//
// That window is not theoretical. Measured here: a plain
// `git checkout HEAD -- gaps.d/` printed pre-commit's "Stashing unstaged
// files" / "Restored changes from" pair and ran three unrelated hooks, for an
// operation that changed no index and made no commit. Separately reproduced on
// 24 Aug with one agent and correct per-workstream worktree isolation already
// in place: a `git checkout -- <file>` in one worktree left it holding a
// byte-identical copy of an uncommitted edit that had only ever been made in
// another. Nothing was lost, but the diagnosis is the expensive part — the
// hooks that report the failure (`check-added-large-files`,
// `check-merge-conflict`) modify nothing and name files the committer never
// touched, so the output points nowhere near the cause.
//
// Running the hook directly removes the window rather than narrowing it. There
// is no snapshot, no patch file, and no shared cache directory involved, so a
// checkout cannot disturb a tree it was never asked to change.
//
// Platform-agnostic: node + git only. The generated hook is `sh`, which is
// Git's own hook convention on every platform including Windows, where Git
// ships the shell that runs it. Nothing shell-specific is committed — only this
// generator, and it is Node.
//
// Usage:
//   node scripts/install-hooks.mjs           install (idempotent)
//   node scripts/install-hooks.mjs --check   report without writing

import { execFileSync } from "node:child_process";
import { chmodSync, readFileSync, writeFileSync } from "node:fs";
import { join, resolve } from "node:path";
import { pathToFileURL } from "node:url";

/** Marks a hook as generated here, so reinstalling can recognise its own work. */
export const MARKER = "generated by scripts/install-hooks.mjs";

/** The hooks this script owns, rather than pre-commit. */
export const OWNED_HOOKS = ["post-checkout"];

/**
 * The `post-checkout` hook body.
 *
 * Both guards are deliberate. Checking out a commit that predates the script —
 * or any tree without it — must not spray an error over an otherwise ordinary
 * checkout, and Git ignores this hook's exit code for the checkout it has
 * already performed, so failing loudly would achieve nothing but noise. Git
 * runs the hook from the top of the working tree, which is why the relative
 * path resolves in a freshly created worktree as well as an existing one.
 */
export const postCheckoutHook = () =>
  [
    "#!/bin/sh",
    `# ${MARKER} — do not edit; re-run that script to update.`,
    "#",
    "# Deliberately NOT a pre-commit hook: pre-commit would snapshot and restore",
    "# the whole working tree around a checkout that commits nothing.",
    "",
    "[ -f scripts/worktree-owner.mjs ] || exit 0",
    "command -v node > /dev/null 2>&1 || exit 0",
    "",
    'exec node scripts/worktree-owner.mjs --stage=post-checkout "$@"',
    "",
  ].join("\n");

/** Whether a hook file on disk is the one this script generates. */
export const isOwnedHook = (contents) =>
  typeof contents === "string" && contents.includes(MARKER);

/**
 * What installing would change, given a reader over the hooks directory.
 *
 * Pure over the reader so both the fresh-checkout and the
 * pre-commit-still-owns-it cases are testable without a repository. The second
 * is the one that matters on an existing clone: `pre-commit install` wrote a
 * `post-checkout` shim there before this script existed, and leaving it would
 * silently keep the snapshot behaviour while everything reported healthy.
 */
export const planInstall = (readHook, hooks = OWNED_HOOKS) =>
  hooks
    .map((hook) => {
      const existing = readHook(hook);
      if (isOwnedHook(existing)) return { hook, action: "current" };
      return {
        hook,
        action: existing === null ? "create" : "replace",
        replacing: existing === null ? null : describeExisting(existing),
      };
    })
    .filter(Boolean);

const describeExisting = (contents) =>
  contents.includes("File generated by pre-commit")
    ? "pre-commit's generated shim"
    : "an unrecognised hook";

/** Read hooks from a resolved directory; absent or unreadable reads as null. */
export const readHookFrom = (hooksDir) => (hook) => {
  try {
    return readFileSync(join(hooksDir, hook), "utf8");
  } catch {
    return null;
  }
};

/**
 * The hooks directory Git will actually use.
 *
 * `hooks` is a common path, so every linked worktree resolves to the same
 * directory — which is the point: one install covers the whole fleet of
 * worktrees attached to this clone.
 */
export const resolveHooksDir = (repoRoot) =>
  resolve(
    repoRoot,
    execFileSync("git", ["rev-parse", "--git-path", "hooks"], {
      cwd: repoRoot,
      encoding: "utf8",
    }).trim(),
  );

const main = () => {
  const check = process.argv.includes("--check");
  let repoRoot;
  try {
    repoRoot = execFileSync("git", ["rev-parse", "--show-toplevel"], {
      encoding: "utf8",
    }).trim();
  } catch {
    console.error("install-hooks: not a git repository");
    process.exit(2);
  }

  const hooksDir = resolveHooksDir(repoRoot);
  const plan = planInstall(readHookFrom(hooksDir));
  const pending = plan.filter((step) => step.action !== "current");

  if (pending.length === 0) {
    console.log(
      `install-hooks: ${plan.length} hook(s) already current in ${hooksDir}`,
    );
    return;
  }

  if (check) {
    for (const step of pending) {
      console.error(
        `install-hooks: ${step.hook} would be ${step.action}d` +
          (step.replacing ? ` (currently ${step.replacing})` : ""),
      );
    }
    console.error("install-hooks: run `node scripts/install-hooks.mjs`");
    process.exit(1);
  }

  for (const step of pending) {
    const path = join(hooksDir, step.hook);
    writeFileSync(path, postCheckoutHook(), "utf8");
    // Unix needs the execute bit; Windows ignores the mode, and Git runs the
    // hook through its bundled shell regardless.
    try {
      chmodSync(path, 0o755);
    } catch {
      /* mode is not meaningful on this platform */
    }
    console.log(
      `install-hooks: ${step.action}d ${step.hook}` +
        (step.replacing ? ` (was ${step.replacing})` : ""),
    );
  }
};

if (
  process.argv[1] &&
  import.meta.url === pathToFileURL(process.argv[1]).href
) {
  main();
}
