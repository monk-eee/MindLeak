//! Export the active constitution as committed-friendly markdown, and the
//! documentation-node predicate that keeps shared prose out of drift verdicts.

use crate::controls::Control;
use crate::model::Goal;
use crate::waiver::Waiver;
use crate::{ConstitutionStatus, GoalKind, Lodestar, Result};

impl Lodestar {
    /// Render the active constitution as committed-friendly markdown; optionally
    /// write it to `path`.
    pub fn export_constitution(&self, path: Option<&str>) -> Result<String> {
        let status = self.constitution_status()?;
        let goals = self.get_constitution()?;
        // Gathered per clause rather than globally: a control belongs to the
        // clause it enforces, and an export that lists them separately makes the
        // reader rejoin them by hand.
        let mut controls = Vec::with_capacity(goals.len());
        for goal in &goals {
            controls.push(self.clause_controls(&goal.id)?);
        }
        let waivers = self.live_waivers()?;
        let markdown = render_constitution(&status, &goals, &controls, &waivers);
        if let Some(p) = path {
            if let Some(parent) = std::path::Path::new(p).parent() {
                std::fs::create_dir_all(parent)?;
            }
            std::fs::write(p, &markdown)?;
        }
        Ok(markdown)
    }
}

/// Documentation artifacts — markdown, and the root operational/meta files —
/// never drive a *drift* verdict: shared prose is touched by everyone, and
/// failing on it would make CHANGELOG.md uneditable without a covering task.
/// They are still bindable and still count in scope for the goal they were
/// bound to (ADR-0060) — the exclusion is about drift, not about governance.
/// This is derived, never enforced by mutating stored bindings — nothing is
/// deleted, so it can never clobber a legitimately-recorded binding.
pub(crate) fn is_documentation_node(node_id: &str) -> bool {
    let path = node_id.strip_prefix("artifact:").unwrap_or(node_id);
    let file = path.rsplit('/').next().unwrap_or(path);
    path.to_ascii_lowercase().ends_with(".md") || matches!(file, "LICENSE" | "CODEOWNERS")
}

/// Render the active constitution as committed-friendly markdown, grouped by
/// kind (invariants first — the hardest constraints lead).
///
/// SPEC-CONSTITUTION §13 requires the active constitution to be exportable,
/// diffable, and **self-contained**. A list of clause statements is none of
/// those: a reviewer handed one cannot tell which constitutional version it is,
/// where a clause came from, what mechanically enforces it, or which exceptions
/// are currently live — so it cannot be audited from, which is the only reason
/// the export exists.
///
/// Absent values are rendered as `not recorded` rather than omitted. The
/// migration that created the first version deliberately invents neither
/// rationale nor authority (§12.1 task 1), and a document that silently drops
/// the empty fields would disguise that as completeness.
fn render_constitution(
    status: &ConstitutionStatus,
    goals: &[Goal],
    controls: &[Vec<Control>],
    waivers: &[Waiver],
) -> String {
    let or_absent = |value: &Option<String>| -> String {
        value
            .as_deref()
            .filter(|v| !v.trim().is_empty())
            .unwrap_or("_not recorded_")
            .to_string()
    };

    let mut out = String::from("# Constitution\n\n");
    out.push_str("> Generated by Lodestar from the active Intent Plane. Do not edit by hand.\n\n");

    out.push_str("## Version\n\n");
    match &status.version {
        Some(version) => {
            out.push_str(&format!(
                "- Constitution: `{}` (v{}, {:?})\n",
                version.id, version.version, version.status
            ));
            out.push_str(&format!("- Clauses: {}\n", status.clause_count));
            out.push_str(&format!(
                "- Created by: {} at {}\n",
                or_absent(&version.created_by),
                version.created_at
            ));
            out.push_str(&format!(
                "- Activated by: {}{}\n",
                or_absent(&version.activated_by),
                version
                    .activated_at
                    .map(|at| format!(" at {at}"))
                    .unwrap_or_default()
            ));
            out.push_str(&format!(
                "- Project identity: {}\n",
                or_absent(&version.project_identity)
            ));
            out.push_str(&format!("- Purpose: {}\n", or_absent(&version.purpose)));
            out.push_str(&format!("- Preamble: {}\n", or_absent(&version.preamble)));
        }
        // `Absent` and `Draft` are not failures to hide: an ungoverned
        // repository must never read as governed (§13).
        None => out.push_str(&format!(
            "- No active constitution (state: {:?}).\n",
            status.state
        )),
    }
    out.push('\n');

    for (kind, heading) in [
        (GoalKind::Invariant, "## Invariants"),
        (GoalKind::Constraint, "## Constraints"),
        (GoalKind::Objective, "## Objectives"),
        (GoalKind::Principle, "## Principles"),
    ] {
        let group: Vec<(usize, &Goal)> = goals
            .iter()
            .enumerate()
            .filter(|(_, g)| g.kind == kind)
            .collect();
        if group.is_empty() {
            continue;
        }
        out.push_str(heading);
        out.push_str("\n\n");
        for (index, g) in group {
            out.push_str(&format!("- **{}** (`{}`, v{})\n", g.title, g.id, g.version));
            out.push_str(&format!("  {}\n", g.statement));
            out.push_str(&format!(
                "  - Provenance: {:?}, constitution {}\n",
                g.origin,
                or_absent(&g.constitution_version)
            ));
            out.push_str(&format!(
                "  - Consequence: {}\n",
                g.consequence
                    .map(|c| format!("{c:?}"))
                    .unwrap_or_else(|| "_not recorded_".to_string())
            ));
            out.push_str(&format!(
                "  - Waivable: {}\n",
                if g.waivable {
                    format!("yes, by {}", or_absent(&g.waiver_authority))
                } else {
                    "no".to_string()
                }
            ));
            let bound = controls.get(index).map(Vec::as_slice).unwrap_or(&[]);
            if bound.is_empty() {
                out.push_str("  - Controls: _none_\n");
            } else {
                for control in bound {
                    out.push_str(&format!(
                        "  - Control: `{}` ({:?}, {:?}, {:?}, v{})\n",
                        control.id, control.kind, control.power, control.status, control.version
                    ));
                }
            }
        }
        out.push('\n');
    }

    out.push_str("## Active waivers\n\n");
    if waivers.is_empty() {
        out.push_str("_None._\n");
    } else {
        for waiver in waivers {
            out.push_str(&format!(
                "- `{}` on `{}` — {} (approved by {}, expires {})\n",
                waiver.id, waiver.clause_id, waiver.reason, waiver.approved_by, waiver.expires_at
            ));
        }
    }
    out.push('\n');
    out
}
